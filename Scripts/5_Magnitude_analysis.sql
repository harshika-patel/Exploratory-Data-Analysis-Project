 --Find total customers by countries
 select country,count(customer_id) totalCustomer from gold.dim_customers
 group by country
 select country,count(customer_key) totalCustomer from gold.dim_customers
 group by country
 order by totalCustomer desc
 --Find total customers by gender
 select gender,count(customer_key) totalCustomer from gold.dim_customers
 group by gender
 order by totalCustomer desc
 --find total product by category
 select category ,count(product_key) TotalProduct from gold.dim_products
  group by category
  order by TotalProduct desc
 --what is the avegare costs in each category
 select category,avg(cost) avgCost from gold.dim_products
 group by category
   order by avgCost desc
 --what is the total revenue generated for each category
 select p.category,sum(s.Sales_amount) totalRevenue from gold.fact_sales s left join gold.dim_products p
 on p.product_key=s.product_key
  group by p.category
    order by totalRevenue desc
 --find the total revenue is generated by each customer
 

 select c.customer_key,c.first_name,c.last_name,sum(f.Sales_amount) TotalRevenue from gold.fact_sales f left join gold.dim_customers c
 on f.customer_key=c.customer_id
 group by c.customer_key,c.first_name,c.last_name
 order by TotalRevenue desc
 --what is the disribution of sold items across countries
 select c.country,sum(f.quantity) totalSale
 from gold.fact_sales f left join  gold.dim_customers c
 on c.customer_key=f.customer_key
 group by c.country
 order by totalSale desc
 /*1. Low Cardinality Dimensions
What it means: A column with very few unique values spread across thousands or millions of rows. The values repeat heavily.

Examples from your Gold Layer:

dim_customers.gender (Only a few values: Male, Female, N/A)

dim_customers.marital_status (Single, Married, Divorced)

dim_products.category (Electronics, Clothing, Home, etc.)

dim_customers.country (Canada, United States, Germany)
2. High Cardinality Dimensions
What it means: A column where almost every row has a unique value (or a very high number of distinct values relative to the total row count).

Examples from your Gold Layer:

dim_customers.customer_key or customer_number (Every customer has a unique ID)

dim_products.product_number / product_name (Each product is distinct)

birthdate (While dates repeat across customers, it still has hundreds or thousands of unique daily values)

fact_sales.order_number*/
